/**
 * Текущий момент времени как реактивное значение (bigplan.md, пункт 25).
 *
 * Единый движок отложенных задач не хранит прогресс — он вычисляет его из
 * `startedAt + duration`. Значит, состояние во время ожидания НЕ МЕНЯЕТСЯ, и панель,
 * подписанная на стор, не перерисуется: полоса прогресса замерла бы до самого конца.
 * Этот хук — недостающий источник изменения: он двигает не данные, а «сейчас».
 *
 * Частота — параметр, а не константа: очередь кораблей идёт минутами, стройка зданий —
 * секундами, и обновлять первую 10 раз в секунду значит платить за перерисовку впустую.
 */

import { useEffect, useState } from 'react';

export function useNowTicker(intervalMs = 1000): number {
  const [now, setNow] = useState(() => Date.now());

  useEffect(() => {
    const id = setInterval(() => setNow(Date.now()), Math.max(100, intervalMs));
    return () => clearInterval(id);
  }, [intervalMs]);

  return now;
}
