/**
 * ОГРАНИЧЕНИЕ КАМЕРЫ СЕТКИ: карту можно тащить по всему экрану независимо от масштаба.
 *
 * ЧТО БЫЛО СЛОМАНО
 * Камера жёстко привязывалась к вьюпорту, и перетаскивание ломалось в обе стороны от
 * «нормального» масштаба:
 *   - сетка мельче экрана (отдалились) — координаты камеры ПЕРЕЗАПИСЫВАЛИСЬ на центрирование
 *     вьюпорта, то есть тащить было нечего: курсор двигался, карта стояла на месте;
 *   - сетка крупнее экрана (приблизились) — край сетки нельзя было отвести от края экрана,
 *     и до угловой клетки нельзя было дотянуться в центр, где не мешают боковые панели.
 * Тем же центрированием молча съедались «перейти к базе» и первичная подгонка: они ставят базу
 * в центр экрана, а следующий за ними clamp возвращал в центр сетку.
 *
 * КАК СЕЙЧАС
 * Свободное панорамирование с единственным правилом: сетка не уезжает из кадра целиком —
 * её пересечение с вьюпортом по каждой оси не меньше KEEP_VISIBLE_PX. Иначе игрок получает
 * пустой экран и читает это как поломку рендера, а не как «карта левее».
 */

/**
 * Сколько пикселей сетки обязано остаться в кадре. Порядка одной клетки (HEX_SIZE = 64) —
 * заметный «язычок», за который карту видно и можно вернуть тем же перетаскиванием.
 */
export const KEEP_VISIBLE_PX = 64;

export type CameraRect = { readonly w: number; readonly h: number };

/**
 * Позиция мира на экране (пиксели вьюпорта, левый-верхний угол мира), ограниченная так, чтобы
 * сетка не пропала из кадра.
 *
 * @param x            желаемая позиция мира по X
 * @param y            желаемая позиция мира по Y
 * @param viewport     размер вьюпорта в пикселях рендерера
 * @param scaledWorld  размер мира УЖЕ с учётом зума
 */
export function clampCamera(
  x: number,
  y: number,
  viewport: CameraRect,
  scaledWorld: CameraRect,
  keepVisiblePx: number = KEEP_VISIBLE_PX,
): { x: number; y: number } {
  return {
    x: clampAxis(x, viewport.w, scaledWorld.w, keepVisiblePx),
    y: clampAxis(y, viewport.h, scaledWorld.h, keepVisiblePx),
  };
}

function clampAxis(pos: number, viewport: number, scaledWorld: number, keepVisiblePx: number): number {
  /*
   * Требуемое пересечение обрезаем по min(мир, вьюпорт): при сильном отдалении сама сетка
   * может быть уже keepVisiblePx, и без обрезки допустимый диапазон стал бы пустым (min > max),
   * то есть clamp вернул бы бессмысленное значение и камеру бы дёргало.
   */
  const keep = Math.min(keepVisiblePx, scaledWorld, viewport);
  const min = keep - scaledWorld;
  const max = viewport - keep;
  if (pos < min) return min;
  if (pos > max) return max;
  return pos;
}
