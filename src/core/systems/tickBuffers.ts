/**
 * БУФЕРЫ РЕСУРСОВ ВНУТРИ ТИКА (bigplan.md, пункт 22).
 *
 * Ресурсы хранятся не числами, а строками: `buffers["base"]["ore"] = "1234.5"`. Строка —
 * потому что значения выходят далеко за double (см. bigNumber) и обязаны переживать JSON
 * сохранения без потерь. Цена — разбор на каждое чтение, а тик читает буферы тысячи раз
 * за кадр.
 *
 * ЧТО ЗДЕСЬ РЕШЕНО И ПОЧЕМУ ЭТО НЕ ПРОСТО ОБЁРТКА
 *
 * 1. КЭШ РАЗБОРА. Одна и та же строка превращается в Decimal один раз за тик. На базе с
 *    сотней клеток это разница между тысячами вызовов конструктора и десятками.
 *
 * 2. КОПИРОВАНИЕ ПРИ ПЕРВОЙ ЗАПИСИ. Объект буферов клетки копируется не на каждую запись,
 *    а один раз, при первом изменении. Наивный `{...bufs[key]}` на каждую запись давал бы
 *    сотни объектов на кадр; полное копирование заранее — столько же, но ещё и для клеток,
 *    которых никто не касался. При этом ИСХОДНЫЙ объект из стора не мутируется никогда —
 *    иначе предыдущее состояние менялось бы задним числом.
 *
 * 3. НЕОТРИЦАТЕЛЬНОСТЬ НА ЗАПИСИ. Значение кламается в ноль ЗДЕСЬ, а не в вызывающем коде.
 *    Отрицательный буфер — это не «долг», а тихая порча состояния: он уедет в сохранение и
 *    вылезет через несколько загрузок как отрицательный склад.
 *
 * 4. REBIND. Тик несколько раз заменяет объект буферов целиком (обрезка по вместимости
 *    складов, эффекты случайных событий). После такой замены владение теряется: в новом
 *    объекте лежат ЧУЖИЕ объекты клеток, и писать в них по месту нельзя. `rebind` сбрасывает
 *    учёт владения — без него порча состояния была бы редкой, тихой и невоспроизводимой.
 *
 * Раньше всё это жило замыканиями внутри `set` тика: протестировать было нечем, а любой
 * новый вызывающий легко заводил вторую, чуть другую копию правил.
 */

import type Decimal from 'break_eternity.js';
import { D } from '../math/format';
import type { ResourceType } from '../gameTypes';

/** Буферы: ключ клетки (или `'base'`) → ресурс → десятичная строка. */
export type BufferMap = Record<string, Partial<Record<ResourceType, string>>>;

const ZERO = D(0);

export interface BufferAccess {
  /** Прочитать значение. Отсутствующее — ноль. */
  get: (buffers: BufferMap, key: string, resource: ResourceType) => Decimal;
  /**
   * Записать значение (отрицательное кламается в ноль) и вернуть тот же объект —
   * подпись сохранена для цепочек `buffers = set(buffers, ...)`.
   */
  set: (buffers: BufferMap, key: string, resource: ResourceType, value: Decimal) => BufferMap;
  /**
   * Сообщить, что объект буферов заменён целиком: учёт владения сбрасывается, и первая
   * же запись в клетку снова скопирует её объект.
   */
  rebind: () => void;
}

/**
 * Создать доступ к буферам на время одного тика.
 *
 * Объект буферов НЕ принадлежит модулю: он остаётся у вызывающего (тик пересоздаёт и
 * заменяет его несколько раз). Модуль хранит только то, что нельзя вывести из объекта, —
 * кэш разбора и учёт того, какие клетки уже скопированы.
 */
export function createBufferAccess(): BufferAccess {
  const owned = new Set<string>();
  const parsed = new Map<string, Decimal>();

  return {
    get(buffers, key, resource) {
      const raw = buffers[key]?.[resource];
      if (raw == null) return ZERO;
      let cached = parsed.get(raw);
      if (!cached) {
        cached = D(raw);
        parsed.set(raw, cached);
      }
      return cached;
    },

    set(buffers, key, resource, value) {
      if (!owned.has(key)) {
        buffers[key] = { ...(buffers[key] ?? {}) };
        owned.add(key);
      }
      buffers[key]![resource] = value.max(ZERO).toString();
      return buffers;
    },

    rebind() {
      owned.clear();
    },
  };
}
